class I18nManager:
    def __init__(self, lang="ko"):
        self.lang = lang if lang in LANGUAGES else "ko"

    def set_language(self, lang):
        if lang in LANGUAGES:
            self.lang = lang

    def t(self, key, **kwargs):
        text = LANGUAGES.get(self.lang, {}).get(key, key)
        if kwargs:
            text = text.format(**kwargs)
        return text